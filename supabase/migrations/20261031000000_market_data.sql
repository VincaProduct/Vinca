-- Market Pulse data entered by admins each month (Dashboard → Admin Tools →
-- Market Data), instead of numbers typed into the code.

-- 1. Nifty 50 monthly average P/E for the Market Pulse heatmap
create table if not exists public.nifty_pe_monthly (
  month date primary key check (extract(day from month) = 1),
  pe numeric(6,2) not null check (pe > 0 and pe < 200),
  source text not null default 'NSE Indices',
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 2. Month-end P/E and 5-year median P/E of four indices, both entered by
--    an admin each month, for the "P/E vs 5-year median" table
create table if not exists public.index_pe_monthly (
  id uuid primary key default gen_random_uuid(),
  index_code text not null check (index_code in ('NIFTY50', 'NIFTYMIDCAP150', 'NIFTYSMALLCAP250', 'NIFTY500')),
  month date not null check (extract(day from month) = 1),
  as_of_date date not null,
  pe numeric(6,2) not null check (pe > 0 and pe < 200),
  median_pe numeric(6,2) not null check (median_pe > 0 and median_pe < 200),
  source text not null default 'NSE Indices',
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (index_code, month)
);

-- Every change to a saved index P/E or median is logged (written by the trigger below)
create table if not exists public.index_pe_edits (
  id uuid primary key default gen_random_uuid(),
  row_id uuid not null,
  old_pe numeric(6,2),
  new_pe numeric(6,2),
  old_median_pe numeric(6,2),
  new_median_pe numeric(6,2),
  changed_by uuid,
  changed_at timestamptz not null default now()
);

create or replace function public.log_index_pe_edit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.updated_at := now();
  if new.pe is distinct from old.pe or new.median_pe is distinct from old.median_pe then
    insert into public.index_pe_edits (row_id, old_pe, new_pe, old_median_pe, new_median_pe, changed_by)
    values (old.id, old.pe, new.pe, old.median_pe, new.median_pe, auth.uid());
  end if;
  return new;
end;
$$;

drop trigger if exists index_pe_monthly_log_edit on public.index_pe_monthly;
create trigger index_pe_monthly_log_edit
  before update on public.index_pe_monthly
  for each row execute function public.log_index_pe_edit();

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists nifty_pe_monthly_touch on public.nifty_pe_monthly;
create trigger nifty_pe_monthly_touch
  before update on public.nifty_pe_monthly
  for each row execute function public.touch_updated_at();

-- Anyone can read; only super admins can add, change or remove
alter table public.nifty_pe_monthly enable row level security;
alter table public.index_pe_monthly enable row level security;
alter table public.index_pe_edits enable row level security;

drop policy if exists "Anyone can read Nifty P/E" on public.nifty_pe_monthly;
create policy "Anyone can read Nifty P/E" on public.nifty_pe_monthly for select using (true);
drop policy if exists "Super admins manage Nifty P/E" on public.nifty_pe_monthly;
create policy "Super admins manage Nifty P/E" on public.nifty_pe_monthly for all
  using (has_role(auth.uid(), 'super_admin'::app_role))
  with check (has_role(auth.uid(), 'super_admin'::app_role));

drop policy if exists "Anyone can read index P/E" on public.index_pe_monthly;
create policy "Anyone can read index P/E" on public.index_pe_monthly for select using (true);
drop policy if exists "Super admins manage index P/E" on public.index_pe_monthly;
create policy "Super admins manage index P/E" on public.index_pe_monthly for all
  using (has_role(auth.uid(), 'super_admin'::app_role))
  with check (has_role(auth.uid(), 'super_admin'::app_role));

drop policy if exists "Super admins read P/E edits" on public.index_pe_edits;
create policy "Super admins read P/E edits" on public.index_pe_edits for select
  using (has_role(auth.uid(), 'super_admin'::app_role));

